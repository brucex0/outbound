#!/usr/bin/env node

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import process from "node:process";

const root = resolve(dirname(new URL(import.meta.url).pathname), "..");
const catalogPath = join(root, "ios/Outbound/Outbound/Localizable.xcstrings");
const resourceRoot = join(root, "android/app/src/main/res");
const checkOnly = process.argv.includes("--check");

const locales = [
  { apple: "en", android: "values" },
  { apple: "es", android: "values-es" },
  { apple: "zh-Hans", android: "values-zh-rCN" },
];

// Keep this list deliberately scoped. Add an entry only when Android ships the
// corresponding surface; the iOS catalog remains the translation authority.
