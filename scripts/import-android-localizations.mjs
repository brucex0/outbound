// These are intentional Android provider substitutions, reviewed alongside
// catalog imports so each supported locale ships together.
const androidStrings = {
  auth_continue_with_google: {
    en: "Continue with Google",
    es: "Continuar con Google",
    "zh-Hans": "使用 Google 继续",
  },
  auth_google_sign_in_failed: {
    en: "Google sign-in could not be completed. Please try again.",
    es: "No se pudo completar el inicio de sesión con Google. Inténtalo de nuevo.",
    "zh-Hans": "无法完成 Google 登录。请重试。",
  },
  auth_google_sign_in_unavailable: {
    en: "Google sign-in is unavailable in this build.",
    es: "El inicio de sesión con Google no está disponible en esta versión.",
    "zh-Hans": "此版本暂不支持 Google 登录。",
  },
  auth_session_expired: {
    en: "Your session expired. Sign in again to continue.",
    es: "Tu sesión ha caducado. Vuelve a iniciar sesión para continuar.",
    "zh-Hans": "登录已过期，请重新登录后继续。",
  },
};

const catalog = JSON.parse(await readFile(catalogPath, "utf8"));

function localizedValue(key, locale) {
  const entry = catalog.strings[key];
  if (!entry) throw new Error(`Missing iOS catalog entry: ${key}`);
  const unit = entry.localizations?.[locale]?.stringUnit;
  if (unit?.state === "translated" && unit.value) return unit.value;
  if (locale === catalog.sourceLanguage && !entry.localizations?.[locale]) return key;
  throw new Error(`Missing translated ${locale} value for: ${key}`);
}

function androidFormat(value) {
  let stringIndex = 0;
  let integerIndex = 0;
  const formatted = value
    .replace(/%lld/g, () => `%${++integerIndex}$d`)
    .replace(/%@/g, () => `%${++stringIndex}$s`);
  return formatted
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("'", "\\'");
}

function render(locale) {
  const rows = [];
  for (const [name, key] of Object.entries(importedStrings)) {
    rows.push(`    <string name="${name}">${androidFormat(localizedValue(key, locale))}</string>`);
  }
  for (const [name, translations] of Object.entries(androidStrings)) {
    rows.push(`    <string name="${name}">${androidFormat(translations[locale])}</string>`);
  }
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by scripts/import-android-localizations.mjs. Do not edit by hand. -->",
    "<resources>",
    ...rows,
    "</resources>",
    "",
  ].join("\n");
}

let stale = false;
for (const locale of locales) {
  const outputPath = join(resourceRoot, locale.android, "auth_strings.xml");
  const expected = render(locale.apple);
  let actual = "";
  try {
    actual = await readFile(outputPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (actual === expected) continue;
  stale = true;
  if (!checkOnly) {
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, expected);
  }
  process.stderr.write(`${checkOnly ? "stale" : "updated"}: ${outputPath}\n`);
}

if (checkOnly && stale) process.exitCode = 1;
