#!/usr/bin/env python3
"""Generate bounded model context for each runtime from the shared feature catalog."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
context = (root / 'shared/assistant/product-knowledge.txt').read_text().strip()
header = '// Generated by scripts/generate-assistant-knowledge.py; do not edit.\n'
outputs = {
    'backend/src/services/assistantProductKnowledge.ts': header + 'export const assistantProductKnowledge = ' + json.dumps(context, ensure_ascii=False) + ';\n',
    'ios/Outbound/Outbound/App/AssistantProductKnowledge.swift': header + 'enum AssistantProductKnowledge {\n    static let context = """\n' + context + '\n"""\n}\n',
    'android/feature/assistant/src/main/kotlin/com/plainstride/outbound/feature/assistant/AssistantProductKnowledge.kt': header + 'package com.plainstride.outbound.feature.assistant\n\ninternal object AssistantProductKnowledge {\n    const val context = """\n' + context + '\n"""\n}\n',
}
if '--check' in sys.argv:
    stale = [path for path, content in outputs.items() if not (root / path).exists() or (root / path).read_text() != content]
    if stale:
        raise SystemExit('Regenerate assistant knowledge: ' + ', '.join(stale))
else:
    for path, content in outputs.items():
        (root / path).write_text(content)
